my ($lang, $file) = @ARGV;
die "usage: perl translate.pl <lang> <file>\n" unless $lang && $file && $T{$lang};

open(my $fh, '<:encoding(UTF-8)', $file) or die "cannot open $file: $!";
local $/;
my $content = <$fh>;
close $fh;

for my $pair (@{$T{$lang}}) {
  my ($search, $replace) = @$pair;
  my $count = () = $content =~ /\Q$search\E/g;
  warn "WARNING [$lang]: 0 matches for: $search\n" if $count == 0;
  $content =~ s/\Q$search\E/$replace/g;
}

open(my $out, '>:encoding(UTF-8)', $file) or die "cannot write $file: $!";
print $out $content;
close $out;

print "Applied " . scalar(@{$T{$lang}}) . " translation pairs to $file\n";
